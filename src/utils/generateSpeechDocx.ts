function p(
  text: string | (string | { text: string; bold?: boolean; italics?: boolean; color?: string })[],
  options: {
    align?: (typeof AlignmentType)[keyof typeof AlignmentType];
    indentFirstLine?: number;
    before?: number;
    after?: number;
    size?: number;
  } = {}
): Paragraph {
  const fontSize = options.size ?? 28; // 14pt default
  const children =
    typeof text === 'string'
      ? [new TextRun({ text, font: 'Times New Roman', size: fontSize })]
      : text.map((part) =>
          typeof part === 'string'
            ? new TextRun({ text: part, font: 'Times New Roman', size: fontSize })
            : new TextRun({
                text: part.text,
                bold: part.bold,
                italics: part.italics,
                color: part.color,
                font: 'Times New Roman',
                size: fontSize,
              })
        );

  return new Paragraph({
    alignment: options.align ?? AlignmentType.JUSTIFIED,
    indent:
      options.indentFirstLine !== undefined
        ? { firstLine: options.indentFirstLine }
        : { firstLine: 709 },
    spacing: {
      line: 360,
      lineRule: LineRuleType.AUTO,
      before: options.before ?? 0,
      after: options.after ?? 80,
    },
    children,
  });
}

function slideHeaderP(slideTitle: string, timing: string): Paragraph {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    spacing: { line: 320, before: 240, after: 80 },
    shading: {
      type: ShadingType.CLEAR,
      fill: 'E6F4F1',
    },
    border: {
      left: { style: BorderStyle.SINGLE, size: 24, color: '0D9488', space: 8 },
    },
    children: [
      new TextRun({
        text: `  ${slideTitle} `,
        font: 'Times New Roman',
        size: 28,
        bold: true,
        color: '0F2922',
      }),
      new TextRun({
        text: `(${timing})`,
        font: 'Times New Roman',
        size: 24,
        italics: true,
        color: '0F766E',
      }),
    ],
  });
}

